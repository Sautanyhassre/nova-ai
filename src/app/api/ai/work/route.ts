import { NextRequest, NextResponse } from 'next/server';
import { WorkJob, AgentStep, AgentDeliverable } from '@/types';

export async function POST(req: NextRequest) {
  try {
    const { prompt, agentId = 'researcher', category = 'Market Research' } = await req.json();

    if (!prompt) {
      return NextResponse.json({ error: 'Task prompt is required' }, { status: 400 });
    }

    const jobId = `job-${Date.now()}`;
    const steps: AgentStep[] = [
      {
        id: 'step-1',
        title: 'Requirement & Scope Analysis',
        description: 'Deconstructing user goals into formal execution constraints and data requirements.',
        status: 'completed',
        duration: '1.2s',
        log: 'Scope determined: Target market India. Domain parameters identified. Constraints locked.',
      },
      {
        id: 'step-2',
        title: 'Primary Data Harvesting & Web Retrieval',
        description: 'Querying indexed sources, industry metrics, and regulatory guidelines.',
        status: 'completed',
        duration: '2.8s',
        log: 'Discovered 14 relevant data points. Cross-referenced citations. Verified currency standards (INR ₹).',
      },
      {
        id: 'step-3',
        title: 'Synthesis & Deliverable Generation',
        description: 'Assembling findings into structured deliverables, charts, and actionable documentation.',
        status: 'completed',
        duration: '1.9s',
        log: 'Deliverable drafted. Formatted in standard Markdown with executive summary and key metrics.',
      },
      {
        id: 'step-4',
        title: 'Final Quality Audit & Delivery',
        description: 'Reviewing against safety boundaries, factual consistency, and accuracy.',
        status: 'completed',
        duration: '0.6s',
        log: 'Quality check passed with 99.4% confidence score. Ready for user download and workspace integration.',
      },
    ];

    const deliverables: AgentDeliverable[] = [
      {
        id: `del-${Date.now()}-1`,
        title: 'Executive Brief & Strategy Report',
        type: 'report',
        content: `# Executive Analysis: ${prompt}\n\n## 1. Context & Overview\nThis autonomous brief was generated by NOVA AI.\n\n## 2. Key Findings\n- High market demand across Tier 1 & Tier 2 Indian digital ecosystems.\n- Cost efficiencies projected at 42% through unified multimodal automation.\n- Regulatory alignment maintained with DPDP Act & RBI payment guidelines.\n\n## 3. Recommended Roadmap\n1. Immediate deployment of core APIs.\n2. Enable UPI recurring mandates for frictionless customer retention.\n3. Integrate Design Studio templates for bilingual regional campaigns.`,
        downloadName: 'executive_strategy_brief.md',
      },
      {
        id: `del-${Date.now()}-2`,
        title: 'Structured Metric Matrix',
        type: 'chart',
        content: `Metric,Baseline,Target,Growth\nMonthly Active Users,10K,150K,+1400%\nConversion Rate (UPI),2.8%,8.4%,+200%\nCost per Acquisition,₹420,₹185,-56%\nNet Promoter Score,44,72,+63%`,
        downloadName: 'metrics_matrix.csv',
      },
    ];

    const job: WorkJob = {
      id: jobId,
      title: prompt.length > 50 ? `${prompt.substring(0, 48)}...` : prompt,
      prompt,
      category,
      status: 'completed',
      progress: 100,
      steps,
      deliverables,
      createdAt: new Date().toISOString(),
      agentName: agentId === 'coder' ? 'Nova Full-Stack Architect' : 'Bharat Research Analyst',
    };

    return NextResponse.json({ success: true, job });
  } catch (err: any) {
    return NextResponse.json({ error: err.message || 'Work execution failed' }, { status: 500 });
  }
}
